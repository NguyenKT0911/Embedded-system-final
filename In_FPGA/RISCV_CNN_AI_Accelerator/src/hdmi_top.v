`timescale 1ns/1ps

module hdmi_top (
    input  wire        sys_clk,      // 27 MHz onboard
    input  wire        rst,
    input  wire [3:0]  prediction,   // 0..9
    input  wire [6:0]  confidence,   // 0..100 percent
    input  wire        confidence_valid,
    input  wire [6:0]  sample_index,
    input  wire [799:0] image_bits,
    input  wire        image_valid,
    output wire        hdmi_locked,
    output wire        tmds_clk_p,
    output wire        tmds_clk_n,
    output wire [2:0]  tmds_d_p,
    output wire [2:0]  tmds_d_n
);

    wire clk_serial_135m;
    wire clk_pixel_27m;
    wire pll_lock;

    // Gowin rPLL generates 5x bit clock: 27 MHz -> 135 MHz (5x) for 10:1 DDR
    rPLL #(
        .FCLKIN("27"),
        .DEVICE("GW2AR-18C"),
        .DYN_IDIV_SEL("false"),
        .IDIV_SEL(0),
        .DYN_FBDIV_SEL("false"),
        .FBDIV_SEL(4),
        .DYN_ODIV_SEL("false"),
        .ODIV_SEL(4),
        .PSDA_SEL("0000"),
        .DYN_DA_EN("false"),
        .DUTYDA_SEL("1000"),
        .CLKOUT_FT_DIR(1'b1),
        .CLKOUTP_FT_DIR(1'b1),
        .CLKOUT_DLY_STEP(0),
        .CLKOUTP_DLY_STEP(0),
        .CLKOUTD_SRC("CLKOUT"),
        .CLKOUTD_BYPASS("false"),
        .CLKOUT_BYPASS("false"),
        .CLKOUTP_BYPASS("false"),
        .CLKFB_SEL("internal"),
        .DYN_SDIV_SEL(2),
        .CLKOUTD3_SRC("CLKOUT")
    ) u_hdmi_pll (
        .CLKOUT(clk_serial_135m),
        .LOCK(pll_lock),
        .CLKOUTP(),
        .CLKOUTD(),
        .CLKOUTD3(),
        .RESET(rst),
        .RESET_P(1'b0),
        .CLKIN(sys_clk),
        .CLKFB(1'b0),
        .FBDSEL(6'b0),
        .IDSEL(6'b0),
        .ODSEL(6'b0),
        .PSDA(4'b0),
        .DUTYDA(4'b0),
        .FDLY(4'b0)
    );

    // Phase-aligned 27 MHz pixel clock generated by CLKDIV from 135 MHz serial clock
    CLKDIV u_clkdiv_pixel (
        .HCLKIN(clk_serial_135m),
        .RESETN(pll_lock),
        .CALIB(1'b1),
        .CLKOUT(clk_pixel_27m)
    );
    defparam u_clkdiv_pixel.DIV_MODE = "5";
    defparam u_clkdiv_pixel.GSREN = "false";

    assign hdmi_locked = pll_lock;

    // Synchronize reset to clk_pixel domain with pll_lock qualifier
    reg [2:0] rst_pixel_sync;
    always @(posedge clk_pixel_27m or negedge pll_lock) begin
        if (!pll_lock)
            rst_pixel_sync <= 3'b111;
        else
            rst_pixel_sync <= {rst_pixel_sync[1:0], rst};
    end
    wire rst_pixel = rst_pixel_sync[2];

    wire [7:0] rgb_r, rgb_g, rgb_b;
    wire hsync, vsync, de;

    hdmi_digit_renderer u_renderer (
        .clk_pixel(clk_pixel_27m),
        .rst(rst_pixel),
        .prediction(prediction),
        .confidence(confidence),
        .confidence_valid(confidence_valid),
        .sample_index(sample_index),
        .image_bits(image_bits),
        .image_valid(image_valid),
        .rgb_r(rgb_r),
        .rgb_g(rgb_g),
        .rgb_b(rgb_b),
        .hsync(hsync),
        .vsync(vsync),
        .de(de)
    );

    wire [9:0] tmds_r, tmds_g, tmds_b;

    // Blue channel carries HSYNC (c_in[0]) and VSYNC (c_in[1])
    tmds_encoder enc_b (
        .clk(clk_pixel_27m),
        .rst(rst_pixel),
        .data_in(rgb_b),
        .c_in({vsync, hsync}),
        .de(de),
        .data_out(tmds_b)
    );

    // Green channel c_in = 2'b00
    tmds_encoder enc_g (
        .clk(clk_pixel_27m),
        .rst(rst_pixel),
        .data_in(rgb_g),
        .c_in(2'b00),
        .de(de),
        .data_out(tmds_g)
    );

    // Red channel c_in = 2'b00
    tmds_encoder enc_r (
        .clk(clk_pixel_27m),
        .rst(rst_pixel),
        .data_in(rgb_r),
        .c_in(2'b00),
        .de(de),
        .data_out(tmds_r)
    );

    wire oser_clk_q;
    wire [2:0] oser_d_q;

    // 10:1 DDR Serialization using Gowin OSER10 primitives
    OSER10 #(
        .GSREN("false"),
        .LSREN("true")
    ) oser_clk (
        .Q(oser_clk_q),
        .D0(1'b1), .D1(1'b1), .D2(1'b1), .D3(1'b1), .D4(1'b1),
        .D5(1'b0), .D6(1'b0), .D7(1'b0), .D8(1'b0), .D9(1'b0),
        .PCLK(clk_pixel_27m),
        .FCLK(clk_serial_135m),
        .RESET(~pll_lock)
    );

    OSER10 #(
        .GSREN("false"),
        .LSREN("true")
    ) oser_d0 (
        .Q(oser_d_q[0]),
        .D0(tmds_b[0]), .D1(tmds_b[1]), .D2(tmds_b[2]), .D3(tmds_b[3]), .D4(tmds_b[4]),
        .D5(tmds_b[5]), .D6(tmds_b[6]), .D7(tmds_b[7]), .D8(tmds_b[8]), .D9(tmds_b[9]),
        .PCLK(clk_pixel_27m),
        .FCLK(clk_serial_135m),
        .RESET(~pll_lock)
    );

    OSER10 #(
        .GSREN("false"),
        .LSREN("true")
    ) oser_d1 (
        .Q(oser_d_q[1]),
        .D0(tmds_g[0]), .D1(tmds_g[1]), .D2(tmds_g[2]), .D3(tmds_g[3]), .D4(tmds_g[4]),
        .D5(tmds_g[5]), .D6(tmds_g[6]), .D7(tmds_g[7]), .D8(tmds_g[8]), .D9(tmds_g[9]),
        .PCLK(clk_pixel_27m),
        .FCLK(clk_serial_135m),
        .RESET(~pll_lock)
    );

    OSER10 #(
        .GSREN("false"),
        .LSREN("true")
    ) oser_d2 (
        .Q(oser_d_q[2]),
        .D0(tmds_r[0]), .D1(tmds_r[1]), .D2(tmds_r[2]), .D3(tmds_r[3]), .D4(tmds_r[4]),
        .D5(tmds_r[5]), .D6(tmds_r[6]), .D7(tmds_r[7]), .D8(tmds_r[8]), .D9(tmds_r[9]),
        .PCLK(clk_pixel_27m),
        .FCLK(clk_serial_135m),
        .RESET(~pll_lock)
    );

    // Differential Output Buffers for HDMI TMDS
    ELVDS_OBUF u_obuf_clk (.I(oser_clk_q),   .O(tmds_clk_p),   .OB(tmds_clk_n));
    ELVDS_OBUF u_obuf_d0  (.I(oser_d_q[0]), .O(tmds_d_p[0]), .OB(tmds_d_n[0]));
    ELVDS_OBUF u_obuf_d1  (.I(oser_d_q[1]), .O(tmds_d_p[1]), .OB(tmds_d_n[1]));
    ELVDS_OBUF u_obuf_d2  (.I(oser_d_q[2]), .O(tmds_d_p[2]), .OB(tmds_d_n[2]));

endmodule

