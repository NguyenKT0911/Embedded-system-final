module instruction_memory(address, instr);
	input wire [31:0] address;
	output wire [31:0] instr;
	reg [31:0] memory [0:255];
	// x1 = 10;
	// x2 = 3;
	// x10 = -16;
	integer i;
	initial begin
		// nop = addi x0, x0, 0 (no operation)
		for(i = 0; i < 256; i = i + 1)
			memory[i] = 32'h00000013;
		//----------------------------------------------------------------------//
		// Nhap du lieu
		//----------------------------------------------------------------------//
		// addi x1, x0, 10
		// x1 = 10;
		memory[0] = {12'd10, 5'd0, 3'h0, 5'd1, 7'b0010011};
		
		// addi x2, x0, 3
		// x2 = 3;
		memory[1] = {12'd3, 5'd0, 3'h0, 5'd2, 7'b0010011};
		
		// addi x10, x0, -16
		// x10 = -16;
		memory[2] = {-12'd16, 5'd0, 3'h0, 5'd10, 7'b0010011};
		
		//----------------------------------------------------------------------//
		// R-type
		//----------------------------------------------------------------------//
		//add x3, x1, x2
		// x3 = 10 + 3 = 13
		memory[3] = {7'h00, 5'd2, 5'd1, 3'h0, 5'd3, 7'b0110011};
		
		//sub x4, x1, x2
		// x4 = 10 - 3 = 7
		memory[4] = {7'h20, 5'd2, 5'd1, 3'h0, 5'd4, 7'b0110011};
		
		//xor x5, x1, x2
		// x5 = 1010 ^ 0011 = 1001 = 9
		memory[5] = {7'h00, 5'd2, 5'd1, 3'h4, 5'd5, 7'b0110011};
		
		//or x6, x1, x2
		// x6 = 1010 | 0011 = 1011 = 11
		memory[6] = {7'h00, 5'd2, 5'd1, 3'h6, 5'd6, 7'b0110011};
		
		// and x7, x1, x2
		// x7 = 1010 & 0011 = 0010 = 2
		memory[7] = {7'h00, 5'd2, 5'd1, 3'h7, 5'd7, 7'b0110011};
		
		// sll x8, x1, x2
		// 10 << 3 = 10 * (2^3) = 80
		memory[8] = {7'h00, 5'd2, 5'd1, 3'h1, 5'd8, 7'b0110011};
		
		// srl x9, x1, x2
		// 10 >> 3 = 1010 >> 3 = 0001 = 1
		memory[9] = {7'h00, 5'd2, 5'd1, 3'h5, 5'd9, 7'b0110011};
		
		// sra x11, x10, x2
		// -16 >>> 3 = -2
		memory[10] = {7'h20, 5'd2, 5'd10, 3'h5, 5'd11, 7'b0110011};
		
		// slt x12, x10, x2
		// signed: -16 < 3  -> True  => 1
		memory[11] = {7'h00, 5'd2, 5'd10, 3'h2, 5'd12, 7'b0110011};
		
		// sltu x13, x10, x2
		// unsigned:
		// 0xFFFFFFF0 < 3 ? -> 0
		memory[12] = {7'h00, 5'd2, 5'd10, 3'h3, 5'd13, 7'b0110011};
		
		//==================================================
		// I-TYPE ALU
		//==================================================

		// addi x14, x1, -5     => x14 = 5
		memory[13] = {12'hFFB, 5'd1, 3'h0, 5'd14, 7'b0010011};

		// xori x15, x1, 3      => x15 = 9
		memory[14] = {12'd3,   5'd1, 3'h4, 5'd15, 7'b0010011};

		// ori x16, x1, 5       => x16 = 15
		memory[15] = {12'd5,   5'd1, 3'h6, 5'd16, 7'b0010011};

		// andi x17, x1, 6      => x17 = 2
		memory[16] = {12'd6,   5'd1, 3'h7, 5'd17, 7'b0010011};

		// slti x18, x10, -8    => x18 = 1
		memory[17] = {12'hFF8, 5'd10, 3'h2, 5'd18, 7'b0010011};

		// sltiu x19, x2, 5     => x19 = 1
		memory[18] = {12'd5,   5'd2, 3'h3, 5'd19, 7'b0010011};

		// slli x20, x2, 2      => x20 = 12
		memory[19] = {7'h00, 5'd2,  5'd2,  3'h1, 5'd20, 7'b0010011};

		// srli x21, x1, 1      => x21 = 5
		memory[20] = {7'h00, 5'd1,  5'd1,  3'h5, 5'd21, 7'b0010011};

		// srai x22, x10, 2     => x22 = -4
		memory[21] = {7'h20, 5'd2,  5'd10, 3'h5, 5'd22, 7'b0010011};
		
		//==================================================
		// SW va LW
		//==================================================
		// addi x23, x0, 100
		// x23 = 100;
		memory[22] = {12'd100, 5'd0, 3'h0, 5'd23, 7'b0010011};
		
		// addi x24, x0, 50
		// x24 = 50;
		memory[23] = {12'd50, 5'd0, 3'h0, 5'd24, 7'b0010011};
		
		// sw x24, 4(x23)
		// imm = 4 = 12'b0000000 00100
		// imm[11:5] = 0000000
		// imm[4:0]  = 00100
		memory[24] = {7'd0, 5'd24, 5'd23, 3'h2, 5'd4, 7'b0100011}; 
		
		// lw x25, 4(x23)
		memory[25] = {12'd4, 5'd23, 3'h2, 5'd25, 7'b0000011};
		
		//==================================================
		// BEQ
		//==================================================
		// addi x26, x0, 5
		// x26 = 5
		memory[26] = {12'd5, 5'd0, 3'h0, 5'd26, 7'b0010011};

		// addi x27, x0, 5
		// x27 = 5
		memory[27] = {12'd5, 5'd0, 3'h0, 5'd27, 7'b0010011};

		// beq x26, x27, +8
		// x26 == x27 => branch taken
		// PC hien tai = 28*4 = 112
		// PC moi = 112 + 8 = 120 => memory[30]
		// bo qua memory[29]
		memory[28] = {1'b0, 6'b000000, 5'd27, 5'd26, 3'h0, 4'b0100, 1'b0, 7'b1100011};
		
		// Lenh nay PHAI bi bo qua neu BEQ dung
		// addi x28, x0, 100
		memory[29] = {12'd100, 5'd0, 3'h0, 5'd28, 7'b0010011};

		// Day la dich branch
		// addi x29, x0, 50
		memory[30] = {12'd50, 5'd0, 3'h0, 5'd29, 7'b0010011};
		
		//==================================================
		// BEQ KHONG NHAY
		//==================================================

		// addi x30, x0, 7
		// x30 = 7
		memory[31] = {12'd7, 5'd0, 3'h0, 5'd30, 7'b0010011};

		// beq x26, x30, +8
		// x26 = 5, x30 = 7 => khong bang nhau
		// branch NOT taken
		// PC se di PC+4 den memory[33]
		memory[32] = {1'b0, 6'b000000, 5'd30, 5'd26, 3'h0, 4'b0100, 1'b0, 7'b1100011};

		// Lenh nay PHAI chay vi BEQ khong nhay
		// addi x31, x0, 77
		// x31 = 77
		memory[33] = {12'd77, 5'd0, 3'h0, 5'd31, 7'b0010011};
		
		
	end
	
   assign instr = memory[address[9:2]];
endmodule
